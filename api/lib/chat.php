// ------------------------------------------------------------------ admin routes
function chat_admin_row(array $c): array
{
    $last = row('SELECT sender, body, deleted, created_at FROM chat_messages WHERE chat_id = ? ORDER BY id DESC LIMIT 1', [$c['id']]);
    return ['id' => (int) $c['id'], 'userId' => $c['user_id'] ? (int) $c['user_id'] : null, 'name' => $c['name'] ?: 'مهمان', 'phone' => $c['phone'], 'status' => $c['status'],
        'escalated' => (bool) $c['escalated_at'], 'topic' => $c['topic'], 'page' => $c['page'], 'device' => $c['device'], 'rating' => $c['rating'] !== null ? (int) $c['rating'] : null,
        'unread' => (int) $c['admin_unread'], 'count' => (int) val('SELECT COUNT(*) FROM chat_messages WHERE chat_id = ?', [$c['id']]),
        'last' => $last ? ['from' => $last['sender'], 'text' => (int) $last['deleted'] ? '🚫 پیام حذف شد' : mb_substr($last['body'], 0, 90)] : null,
        'createdAt' => ms($c['created_at']), 'updatedAt' => ms($c['updated_at'])];
}
function a_chat_list(): void
{
    require_active('admin');
    $f = str_in('filter', 16);
    $qs = str_in('q', 80);
    $page = max(0, int_in('page'));
    $where = ['1 = 1'];
    $p = [];
    if ($f === 'open') $where[] = "status IN ('waiting','live')";
    elseif ($f === 'bot') $where[] = 'escalated_at IS NULL';
    elseif ($f === 'human') $where[] = 'escalated_at IS NOT NULL';
    elseif ($f === 'closed') $where[] = "status = 'closed'";
    if ($qs !== '') {
        $where[] = '(name LIKE ? OR phone LIKE ? OR topic LIKE ? OR id IN (SELECT chat_id FROM chat_messages WHERE body LIKE ?))';
        $like = '%' . en_digits($qs) . '%';
        array_push($p, $like, $like, $like, $like);
    }
    $list = rows('SELECT * FROM chats WHERE ' . implode(' AND ', $where) . " ORDER BY (status IN ('waiting','live')) DESC, updated_at DESC LIMIT 31 OFFSET " . ($page * 30), $p);
    $more = count($list) > 30;
    $total = (int) val('SELECT COUNT(*) FROM chats');
    $botOnly = (int) val('SELECT COUNT(*) FROM chats WHERE escalated_at IS NULL');
    $stats = ['total' => $total, 'open' => (int) val("SELECT COUNT(*) FROM chats WHERE status IN ('waiting','live')"), 'waiting' => (int) val("SELECT COUNT(*) FROM chats WHERE status = 'waiting'"),
        'today' => (int) val('SELECT COUNT(*) FROM chats WHERE created_at >= ?', [date('Y-m-d 00:00:00')]),
        'botRate' => $total ? round($botOnly / $total * 100) : 0, 'messages' => (int) val('SELECT COUNT(*) FROM chat_messages')];
    // Questions the bot could not answer — candidates for new FAQ lines
    $missed = array_map(function ($r) { return ['text' => $r['body'], 'chatId' => (int) $r['chat_id'], 'at' => ms($r['created_at'])]; },
        rows("SELECT body, chat_id, created_at FROM chat_messages WHERE sender = 'user' AND intent = 'fallback' ORDER BY id DESC LIMIT 15"));
    out(['chats' => array_map('chat_admin_row', array_slice($list, 0, 30)), 'more' => $more, 'stats' => $stats, 'missed' => $missed,
        'quickReplies' => array_values((array) (setting('chat', 'quickReplies') ?: []))]);
}
function a_chat_get(): void
{
    require_active('admin');
    $c = row('SELECT * FROM chats WHERE id = ?', [int_in('id')]);
    if (!$c) fail('گفتگو پیدا نشد.', 404);
    if ((int) $c['admin_unread']) update('chats', ['admin_unread' => 0], 'id = ?', [$c['id']]);
    $user = $c['user_id'] ? row('SELECT * FROM users WHERE id = ?', [$c['user_id']]) : null;
    $info = null;
    if ($user) $info = ['id' => (int) $user['id'], 'name' => $user['name'], 'phone' => $user['phone'], 'role' => $user['role'], 'wallet' => (int) $user['wallet'],
        'orders' => array_map(function ($o) { return ['id' => (int) $o['id'], 'code' => $o['code'], 'title' => $o['title'], 'status' => $o['status']]; }, rows('SELECT id, code, title, status FROM orders WHERE user_id = ? ORDER BY id DESC LIMIT 5', [$user['id']]))];
    out(['chat' => chat_admin_row(row('SELECT * FROM chats WHERE id = ?', [$c['id']])) + ['rev' => (int) $c['rev']], 'messages' => chat_messages((int) $c['id']), 'user' => $info]);
}
function a_chat_poll(): void
{
    require_active('admin');
    $id = int_in('id');
    $res = ['waiting' => (int) val("SELECT COUNT(*) FROM chats WHERE status = 'waiting' OR admin_unread > 0")];
    if ($id && ($c = row('SELECT * FROM chats WHERE id = ?', [$id]))) {
        $full = (int) in('rev', 0) !== (int) $c['rev'];
        $res['messages'] = chat_messages($id, $full ? 0 : int_in('after'));
        $res['full'] = $full;
        $res['chat'] = ['status' => $c['status'], 'rev' => (int) $c['rev']];
        if ((int) $c['admin_unread']) update('chats', ['admin_unread' => 0], 'id = ?', [$id]);
    }
    out($res);
}
function a_chat_send(): void
{
    $me = require_active('admin');
    $c = row('SELECT * FROM chats WHERE id = ?', [int_in('id')]);
    if (!$c) fail('گفتگو پیدا نشد.', 404);
    $text = str_in('text', 4000);
    if ($text === '') fail('پیام خالی است.', 422);
    chat_add((int) $c['id'], 'admin', $text, [], '', (int) $me['id']);
    update('chats', ['status' => 'live', 'escalated_at' => $c['escalated_at'] ?: now(), 'user_unread' => (int) $c['user_unread'] + 1, 'admin_unread' => 0, 'updated_at' => now()], 'id = ?', [$c['id']]);
    if ($c['user_id']) notify((int) $c['user_id'], '💬 پاسخ پشتیبانی: ' . mb_substr($text, 0, 120), 'index.html#support');
    out(['messages' => chat_messages((int) $c['id'], int_in('after'))]);
}
// Only the admin can edit or delete messages; deleting keeps a placeholder so the thread stays readable
function a_chat_edit(): void
{
    require_active('admin');
    $m = row('SELECT * FROM chat_messages WHERE id = ?', [int_in('id')]);
    if (!$m || $m['sender'] !== 'admin' || (int) $m['deleted']) fail('فقط پیام‌های خودتان قابل ویرایش است.', 422);
    $text = str_in('text', 4000);
    if ($text === '') fail('پیام خالی است.', 422);
    update('chat_messages', ['body' => $text, 'edited' => 1], 'id = ?', [$m['id']]);
    q('UPDATE chats SET rev = rev + 1 WHERE id = ?', [$m['chat_id']]);
    done('پیام ویرایش شد.');
}
