// Admin FAQ lines: «keyword, keyword | answer»
function bot_faq(): array
{
    $out = [];
    foreach ((array) (setting('chat', 'faq') ?: []) as $line) {
        $parts = explode('|', (string) $line, 2);
        if (count($parts) < 2 || trim($parts[1]) === '') continue;
        $kws = array_values(array_filter(array_map('trim', preg_split('/[،,]/u', $parts[0]))));
        if ($kws) $out[] = ['kw' => $kws, 'answer' => trim($parts[1])];
    }
    return $out;
}

// Reply for one user message: ['text', 'chips'?, 'links'?, 'human'?, 'intent', 'topic'?]
function bot_reply(string $raw, ?array $user, array $chat): array
{
    $norm = bot_norm($raw);
    $ctx = ['raw' => $raw, 'norm' => $norm, 'user' => $user];
    // Order code in the message → order status straight away
    if (preg_match('/BX\s*-?\s*\d{3,6}/i', en_digits($raw))) return bot_order_answer($raw, $user) + ['intent' => 'track'];

    // Admin FAQ first: exact business knowledge wins
    foreach (bot_faq() as $i => $f) {
        $hits = 0;
        foreach ($f['kw'] as $k) if (bot_has($norm, $k)) $hits++;
        if ($hits) return ['text' => $f['answer'], 'intent' => 'faq' . $i, 'chips' => ['جوابم را گرفتم ✅', 'گفتگو با پشتیبان']];
    }

    $tokens = bot_tokens($norm);
    $scores = [];
    foreach (bot_intents() as $id => $it) {
        $s = 0;
        foreach ($it['kw'] as $k) if (bot_has($norm, $k)) $s += 1 + substr_count(bot_norm($k), ' ') * 0.6;
        $bestEx = 0;
        foreach ($it['ex'] as $ex) {
            $et = bot_tokens(bot_norm($ex));
            if (!$et || !$tokens) continue;
            $ov = count(array_intersect($et, $tokens)) / count($et);
            if ($ov >= 0.5) $bestEx = max($bestEx, $ov * 1.5);
        }
        $s += $bestEx;
        if ($s > 0) $scores[$id] = $s * (!empty($it['weak']) ? 0.6 : 1);
    }
    arsort($scores);
    $top = key($scores);
    $topScore = $top ? $scores[$top] : 0;

    // A service named in the message (or the one we were just talking about)
    [$svc, $svcScore] = bot_find_service($norm);
    if (!$svc && strpos((string) $chat['topic'], 'svc:') === 0 && in_array($top, ['price', 'time'], true)) {
        $sid = substr($chat['topic'], 4);
        foreach (bot_services() as $s) if ($s['id'] === $sid) [$svc, $svcScore] = [$s, 9];
    }
    // Questions about an action (tracking, refund, download…) win over a service that is merely mentioned
    $action = ['track', 'pay_fail', 'refund', 'revisions', 'files', 'shop', 'installment', 'staged', 'discount', 'invoice', 'designer_join', 'seller_join',
        'complaint', 'human', 'login', 'referral', 'designer_choose', 'wallet', 'trust', 'privacy', 'brief', 'portfolio', 'who', 'hosting', 'after_support', 'yes_done', 'thanks', 'bye'];
    $neutral = ['price', 'time', 'order_how', 'greet', 'services', 'ok', 'how_are_you', 'ai', 'about', 'more'];
    if ($svc && (!$top || in_array($top, $neutral, true) || (!in_array($top, $action, true) && $svcScore >= $topScore) || (in_array($top, $action, true) && $topScore < 1))) {
        return bot_service_answer($svc, $top === 'time' ? 'time' : '') + ['intent' => 'service:' . $svc['id']];
    }
    if ($top && $topScore >= 0.6) {
        $ans = bot_intents()[$top]['answer'];
        $r = is_callable($ans) ? $ans($ctx) : $ans;
        return $r + ['intent' => $top];
    }
    // Not understood
    $miss = (int) $chat['misses'] + 1;
    if ($miss >= 2) return ['text' => 'متأسفم، هنوز نتوانستم جواب دقیق سؤالتان را پیدا کنم 🙏 برای اینکه وقتتان تلف نشود، با پشتیبان صحبت کنید تا یک کارشناس مستقیم جوابتان را بدهد.', 'human' => true, 'intent' => 'fallback'];
    return ['text' => 'سؤالتان را کامل متوجه نشدم 🤔 می‌شود کمی واضح‌تر بنویسید؟ مثلاً «قیمت طراحی لوگو»، «سفارشم کجاست» یا «قسطی میشه پرداخت کرد؟»', 'chips' => ['لیست خدمات', 'پیگیری سفارش', 'روش‌های پرداخت', 'گفتگو با پشتیبان'], 'intent' => 'fallback'];
}

// ------------------------------------------------------------------ storage helpers
function chat_msg_out(array $m): array
{
    $meta = jdec($m['meta'] ?? '', []) ?: [];
    return ['id' => (int) $m['id'], 'from' => $m['sender'], 'text' => (int) $m['deleted'] ? '' : $m['body'], 'deleted' => (bool) $m['deleted'], 'edited' => (bool) $m['edited'],
        'chips' => $meta['chips'] ?? [], 'links' => $meta['links'] ?? [], 'human' => !empty($meta['human']), 'at' => ms($m['created_at'])];
}
function chat_messages(int $chatId, int $after = 0): array
{
    return array_map('chat_msg_out', rows('SELECT * FROM chat_messages WHERE chat_id = ? AND id > ? ORDER BY id LIMIT 300', [$chatId, $after]));
}
function chat_add(int $chatId, string $sender, string $body, array $meta = [], string $intent = '', ?int $adminId = null): int
{
    return insert('chat_messages', ['chat_id' => $chatId, 'sender' => $sender, 'admin_id' => $adminId, 'body' => $body, 'meta' => $meta ? jenc($meta) : null,
        'intent' => mb_substr($intent, 0, 40), 'created_at' => now()]);
}
function chat_out(array $c): array
{
    return ['token' => $c['token'], 'status' => $c['status'], 'rev' => (int) $c['rev'], 'unread' => (int) $c['user_unread'], 'name' => $c['name']];
}
// The visitor's chat by token (guest) or their latest open chat (logged in); creates one when asked
function chat_current(bool $create): ?array
{
    $u = me();
    $token = preg_replace('/[^a-f0-9]/', '', (string) in('token', ''));
    $c = $token ? row('SELECT * FROM chats WHERE token = ?', [$token]) : null;
    if ($c && $c['user_id'] && (!$u || (int) $c['user_id'] !== (int) $u['id'])) $c = null; // another account's chat
    if (!$c && $u) $c = row("SELECT * FROM chats WHERE user_id = ? AND status <> 'closed' ORDER BY id DESC LIMIT 1", [$u['id']]);
    if ($c && $u && !$c['user_id']) {
        update('chats', ['user_id' => $u['id'], 'name' => $c['name'] ?: $u['name'], 'phone' => $c['phone'] ?: $u['phone']], 'id = ?', [$c['id']]);
        $c = row('SELECT * FROM chats WHERE id = ?', [$c['id']]);
    }
    if (!$c && $create) {
        $ua = function_exists('ua_info') ? ua_info() : ['device' => ''];
        $id = insert('chats', ['token' => bin2hex(random_bytes(16)), 'user_id' => $u['id'] ?? null, 'name' => $u['name'] ?? '', 'phone' => $u['phone'] ?? '',
            'status' => 'bot', 'page' => mb_substr(str_in('page', 120), 0, 120), 'device' => $ua['device'], 'created_at' => now(), 'updated_at' => now()]);
        $c = row('SELECT * FROM chats WHERE id = ?', [$id]);
    }
    return $c;
}

// ------------------------------------------------------------------ public routes
function r_chat_open(): void
{
    if (empty(setting('chat', 'enabled'))) fail('گفتگوی آنلاین فعلاً غیرفعال است.', 403);
    $c = chat_current(false);
    if (!$c) out(['chat' => null, 'messages' => [], 'me' => me() ? ['name' => me()['name']] : null]);
    if ((int) $c['user_unread']) update('chats', ['user_unread' => 0], 'id = ?', [$c['id']]);
    out(['chat' => chat_out($c), 'messages' => chat_messages((int) $c['id']), 'me' => me() ? ['name' => me()['name']] : null]);
}

function r_chat_send(): void
{
    if (empty(setting('chat', 'enabled'))) fail('گفتگوی آنلاین فعلاً غیرفعال است.', 403);
    rate_limit('chat', 25, 60);
    $text = str_in('text', 2000);
    if ($text === '') fail('پیام خالی است.', 422);
    $c = chat_current(true);
    if ($c['status'] === 'closed') {
        update('chats', ['status' => 'bot', 'misses' => 0], 'id = ?', [$c['id']]);
        $c['status'] = 'bot';
        $c['misses'] = 0;
    }
    $after = (int) in('after', 0);
    $u = me();
    $intent = '';
    if ($c['status'] === 'bot') {
        $r = bot_reply($text, $u, $c);
        $intent = $r['intent'] ?? '';
        $mid = chat_add((int) $c['id'], 'user', $text, [], $intent);
        $meta = array_filter(['chips' => $r['chips'] ?? [], 'links' => $r['links'] ?? [], 'human' => !empty($r['human'])]);
        chat_add((int) $c['id'], 'bot', $r['text'], $meta, $intent);
        $upd = ['misses' => $intent === 'fallback' ? (int) $c['misses'] + 1 : 0, 'updated_at' => now()];
        if (!empty($r['topic'])) $upd['topic'] = $r['topic'];
        if (!empty($r['resolved'])) $upd['rating'] = 5;
        if (!$c['topic'] && empty($r['topic']) && $intent !== 'fallback' && $intent !== 'greet') $upd['topic'] = mb_substr($text, 0, 190);
        update('chats', $upd, 'id = ?', [$c['id']]);
    } else {
        chat_add((int) $c['id'], 'user', $text);
        q('UPDATE chats SET admin_unread = admin_unread + 1, updated_at = ? WHERE id = ?', [now(), $c['id']]);
    }
    $c = row('SELECT * FROM chats WHERE id = ?', [$c['id']]);
    out(['chat' => chat_out($c), 'messages' => chat_messages((int) $c['id'], $after)]);
}

function r_chat_poll(): void
{
    $c = chat_current(false);
    if (!$c) out(['chat' => null, 'messages' => []]);
    $rev = (int) in('rev', 0);
    $after = (int) in('after', 0);
    $full = $rev !== (int) $c['rev'];
    $msgs = chat_messages((int) $c['id'], $full ? 0 : $after);
    if (in('open') && (int) $c['user_unread']) update('chats', ['user_unread' => 0], 'id = ?', [$c['id']]);
    out(['chat' => chat_out($c), 'messages' => $msgs, 'full' => $full]);
}

// Hand the conversation to a person: logged-in users go straight through, guests leave name + phone
function r_chat_escalate(): void
{
    rate_limit('chat-esc', 6, 600);
    $c = chat_current(true);
    $u = me();
    if ($u) {
        $name = $u['name'];
        $phone = $u['phone'];
    } else {
        $name = str_in('name', 120);
        $phone = preg_replace('/\D/', '', en_digits(str_in('phone', 20)));
        if (mb_strlen($name) < 2) fail('نام خود را وارد کنید.', 422);
        if (!preg_match('/^09\d{9}$/', $phone)) fail('شماره موبایل معتبر نیست.', 422);
    }
    $note = str_in('note', 1000);
    $was = $c['status'];
    update('chats', ['name' => $name, 'phone' => $phone, 'status' => in_array($was, ['live', 'waiting'], true) ? $was : 'waiting', 'escalated_at' => $c['escalated_at'] ?: now(),
        'admin_unread' => (int) $c['admin_unread'] + 1, 'updated_at' => now()], 'id = ?', [$c['id']]);
    if ($note !== '') chat_add((int) $c['id'], 'user', $note);
    if (!in_array($was, ['live', 'waiting'], true)) {
        chat_add((int) $c['id'], 'system', 'درخواست گفتگو با پشتیبان ثبت شد' . ($u ? '' : " · {$name}"));
        chat_add((int) $c['id'], 'bot', (string) (setting('chat', 'offline') ?: 'پیام شما به پشتیبانی رسید.'));
        notify_admins("💬 درخواست گفتگوی پشتیبانی از {$name}", 'dashboard.html#support/' . $c['id']);
        if (!empty(setting('chat', 'smsAdmin'))) {
            require_once __DIR__ . '/gateways.php'; // loads the SMS helpers
            sms_admin('admin_support', ['name' => $name, 'phone' => $phone]);
        }
    }
    $c = row('SELECT * FROM chats WHERE id = ?', [$c['id']]);
    out(['chat' => chat_out($c), 'messages' => chat_messages((int) $c['id'], (int) in('after', 0))]);
}

