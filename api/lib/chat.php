function bot_services(): array
{
    static $list = null;
    if ($list !== null) return $list;
    $list = [];
    foreach (catalog(true) as $c) foreach ($c['services'] as $s) $list[] = $s + ['catTitle' => $c['title']];
    return $list;
}
// Best matching service for the text: [service, score] or [null, 0]
function bot_find_service(string $norm): array
{
    $best = null;
    $bestScore = 0;
    foreach (bot_services() as $s) {
        $score = 0;
        foreach (BOT_SERVICE_ALIASES[$s['id']] ?? [] as $a) if (bot_has($norm, $a)) $score = max($score, $a === 'سایت' ? 1.6 : 2 + mb_strlen(bot_norm($a)) / 10);
        if (bot_has($norm, $s['title'])) $score = max($score, 4);
        else {
            $words = array_filter(bot_tokens(bot_norm($s['title'])), function ($w) { return mb_strlen($w) >= 3 && !in_array($w, ['طراحی', 'حرفه', 'ای', 'هوش', 'مصنوعی'], true); });
            $hit = 0;
            foreach ($words as $w) if (bot_has($norm, $w)) $hit++;
            if ($words && $hit && ($hit === count($words) || $hit >= 2)) $score = max($score, 1 + $hit / count($words) * 1.5);
        }
        if ($score > $bestScore) { $bestScore = $score; $best = $s; }
    }
    return $bestScore >= 1.6 ? [$best, $bestScore] : [null, 0];
}
