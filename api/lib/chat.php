// ------------------------------------------------------------------ text helpers
function bot_norm(string $s): string
{
    $s = mb_strtolower(en_digits($s));
    $s = strtr($s, ['ي' => 'ی', 'ك' => 'ک', 'ى' => 'ی', 'ة' => 'ه', 'ۀ' => 'ه', 'أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', "\u{200C}" => ' ', 'ـ' => '']);
    $s = preg_replace('/[\x{064B}-\x{065F}\x{0670}]/u', '', $s);
    $s = preg_replace('/[^\p{L}\p{N}\s-]+/u', ' ', $s);
    return trim(preg_replace('/\s+/u', ' ', $s));
}
const BOT_STOP = ['من', 'شما', 'ما', 'از', 'به', 'با', 'در', 'که', 'را', 'رو', 'و', 'یا', 'این', 'اون', 'ان', 'یه', 'یک', 'هم', 'برای', 'برا', 'تا', 'چه', 'چی', 'چطور', 'چطوری', 'چگونه',
    'است', 'هست', 'هستش', 'میشه', 'می', 'شه', 'شود', 'کنم', 'کنید', 'کنین', 'کن', 'دارم', 'دارید', 'دارین', 'داره', 'میخوام', 'میخواستم', 'خواستم', 'لطفا', 'سلام', 'ببخشید', 'اگه', 'اگر', 'باید', 'بدم', 'بدید',
    'میدید', 'میدین', 'میکنید', 'میکنین', 'دارید', 'دارین', 'هستید', 'بدین', 'بدید', 'بگیرم', 'میتونم', 'میشه', 'ایا', 'خیلی', 'الان', 'کجا', 'کجاست', 'چیه', 'چیست', 'نمیشه', 'نمی', 'بود', 'بشه', 'تو', 'توی', 'اینجا', 'سایت'];
function bot_tokens(string $norm): array
{
    return array_values(array_filter(explode(' ', $norm), function ($w) { return mb_strlen($w) > 1 && !in_array($w, BOT_STOP, true); }));
}
function bot_has(string $norm, string $kw): bool
{
    $kw = bot_norm($kw);
    if ($kw === '') return false;
    // Short words must stand alone; longer ones match at a word start (so suffixes like «قیمتش» still count)
    if (mb_strlen($kw) <= 2) return (bool) preg_match('/(^|\s)' . preg_quote($kw, '/') . '(\s|$)/u', $norm);
    return (bool) preg_match('/(^|\s)' . preg_quote($kw, '/') . '/u', $norm);
}
function bot_money(int $n): string
{
    return fa_digits(number_format($n)) . ' تومان';
}

