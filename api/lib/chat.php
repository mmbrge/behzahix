function a_chat_close(): void
{
    require_active('admin');
    $c = row('SELECT * FROM chats WHERE id = ?', [int_in('id')]);
    if (!$c) fail('گفتگو پیدا نشد.', 404);
    if ($c['status'] === 'closed') {
        update('chats', ['status' => $c['escalated_at'] ? 'live' : 'bot'], 'id = ?', [$c['id']]);
        done('گفتگو دوباره باز شد.');
    }
    chat_add((int) $c['id'], 'system', 'گفتگو توسط پشتیبان بسته شد');
    update('chats', ['status' => 'closed', 'admin_unread' => 0, 'updated_at' => now()], 'id = ?', [$c['id']]);
    done('گفتگو بسته و بایگانی شد.');
}
