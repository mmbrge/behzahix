<?php
// BEHIX — one-time installer. Creates the database tables, the admin account
// and api/config.php. Locks itself once config.php exists.
define('BX', true);
ini_set('display_errors', '0');
session_start();
require __DIR__ . '/api/lib/core.php';
require __DIR__ . '/api/lib/schema.php';
require __DIR__ . '/api/lib/defaults.php';

$configFile = __DIR__ . '/api/config.php';
// Locked once config.php exists and an admin account has been created.
$locked = false;
if (is_file($configFile)) {
    try {
        $c = bx_config()['db'];
        $chk = new PDO("mysql:host={$c['host']};dbname={$c['name']};charset=utf8mb4", $c['user'], $c['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $locked = (bool) $chk->query("SELECT COUNT(*) FROM users WHERE role = 'admin'")->fetchColumn();
    } catch (Throwable $e) {
        $locked = false;
    }
}
$errors = [];
$done = null;
$manualConfig = null;
if (empty($_SESSION['inst'])) $_SESSION['inst'] = bin2hex(random_bytes(16));

$checks = [
    'نسخه PHP ۷٫۴ یا بالاتر' => version_compare(PHP_VERSION, '7.4.0', '>='),
    'افزونه PDO MySQL' => extension_loaded('pdo_mysql'),
    'افزونه mbstring' => extension_loaded('mbstring'),
    'افزونه cURL (درگاه و پیامک)' => extension_loaded('curl'),
    'پوشه uploads قابل نوشتن' => is_dir(__DIR__ . '/uploads') ? is_writable(__DIR__ . '/uploads') : is_writable(__DIR__),
];

$https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off');
$guessUrl = ($https ? 'https' : 'http') . '://' . ($_SERVER['HTTP_HOST'] ?? 'localhost') . rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '/')), '/');
$v = function ($k, $d = '') { return htmlspecialchars((string) ($_POST[$k] ?? $d), ENT_QUOTES, 'UTF-8'); };

if (!$locked && $_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!hash_equals($_SESSION['inst'], (string) ($_POST['t'] ?? ''))) $errors[] = 'نشست منقضی شده است؛ صفحه را دوباره باز کنید.';
    $db = ['host' => trim($_POST['db_host'] ?? 'localhost'), 'name' => trim($_POST['db_name'] ?? ''), 'user' => trim($_POST['db_user'] ?? ''), 'pass' => (string) ($_POST['db_pass'] ?? '')];
    $adminName = trim($_POST['admin_name'] ?? '');
    $adminPhone = preg_replace('/\D/', '', en_digits((string) ($_POST['admin_phone'] ?? '')));
    $adminPass = (string) ($_POST['admin_pass'] ?? '');
    $url = rtrim(trim($_POST['url'] ?? $guessUrl), '/');
    if (!$db['name'] || !$db['user']) $errors[] = 'نام و کاربر پایگاه داده را وارد کنید.';
    if (mb_strlen($adminName) < 2) $errors[] = 'نام مدیر را وارد کنید.';
    if (!preg_match('/^09\d{9}$/', $adminPhone)) $errors[] = 'شماره موبایل مدیر معتبر نیست.';
    if (strlen($adminPass) < 8) $errors[] = 'رمز مدیر باید حداقل ۸ کاراکتر باشد.';
    if (!$errors) {
        try {
            $pdo = new PDO("mysql:host={$db['host']};dbname={$db['name']};charset=utf8mb4", $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        } catch (PDOException $e) {
            $errors[] = 'اتصال به پایگاه داده ناموفق بود: ' . htmlspecialchars($e->getMessage(), ENT_QUOTES, 'UTF-8');
        }
    }
    if (!$errors) {
        $config = ['db' => $db, 'url' => $url, 'secret' => bin2hex(random_bytes(24))];
        $php = "<?php\n// BEHIX configuration — generated by install.php. Keep this file private.\nreturn " . var_export($config, true) . ";\n";
        $pdo->exec("SET time_zone = '+00:00'");
        foreach (bx_schema() as $sql) $pdo->exec($sql);
        if (!is_file($configFile) && !@file_put_contents($configFile, $php)) $manualConfig = $php;
        // core db() reads config.php; load it now so helpers work
        if (!$manualConfig) {
            seed_catalog();
            if (row('SELECT id FROM users WHERE phone = ?', [$adminPhone])) {
                update('users', ['name' => $adminName, 'password_hash' => password_hash($adminPass, PASSWORD_DEFAULT), 'role' => 'admin', 'status' => 'active'], 'phone = ?', [$adminPhone]);
                $adminId = (int) val('SELECT id FROM users WHERE phone = ?', [$adminPhone]);
            } else {
                $adminId = insert('users', ['name' => $adminName, 'phone' => $adminPhone, 'password_hash' => password_hash($adminPass, PASSWORD_DEFAULT),
                    'role' => 'admin', 'status' => 'active', 'hue' => 25, 'created_at' => now()]);
            }
            $general = default_settings()['general'];
            if (!empty($_POST['demo']) && !val('SELECT COUNT(*) FROM users WHERE is_demo = 1')) {
                seed_demo($adminId);
                $general['demoMode'] = true;
            }
            $general['siteNameFa'] = trim($_POST['site_name'] ?? '') ?: $general['siteNameFa'];
            save_setting('general', $general);
            if (!is_dir(__DIR__ . '/uploads')) @mkdir(__DIR__ . '/uploads', 0755, true);
            $done = true;
        }
    }
}
