    <p class="muted lh mt-2">سایت قبلاً نصب شده است. برای امنیت بیشتر، فایل <code>install.php</code> را از هاست حذف کنید.</p>
    <p class="mt-2"><a class="btn btn-primary" href="index.html">رفتن به سایت</a></p>
<?php elseif ($done): ?>
    <div class="success" style="padding:20px 0">
      <span class="success-icon">✓</span>
      <h2>نصب با موفقیت انجام شد!</h2>
