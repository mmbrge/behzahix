      <div class="cta-actions"><a class="btn btn-primary" href="auth.html?next=dashboard.html%23settings">ورود به پنل مدیریت</a><a class="btn btn-ghost" href="index.html">مشاهده سایت</a></div>
    </div>
<?php elseif ($manualConfig): ?>
    <div class="err">جداول ساخته شد اما فایل تنظیمات قابل نوشتن نبود. یک فایل با نام <code>config.php</code> در پوشه <code>api</code> بسازید، متن زیر را داخلش قرار دهید و این صفحه را دوباره ارسال کنید.</div>
    <pre><?= htmlspecialchars($manualConfig, ENT_QUOTES, 'UTF-8') ?></pre>
<?php else: ?>
    <p class="muted lh mt-1">ابتدا در cPanel از بخش <b>MySQL Database Wizard</b> یک پایگاه داده و کاربر بسازید (با دسترسی ALL PRIVILEGES)، سپس اطلاعات را این‌جا وارد کنید.</p>
    <h2>بررسی پیش‌نیازها</h2>
    <ul class="checks"><?php foreach ($checks as $label => $ok): ?><li><span><?= $label ?></span><b class="<?= $ok ? 'ok' : 'bad' ?>"><?= $ok ? '✓' : '✗' ?></b></li><?php endforeach; ?></ul>
    <?php if ($errors): ?><div class="err"><?= implode('<br>', $errors) ?></div><?php endif; ?>
    <form method="post" class="form-grid mt-2" autocomplete="off">
